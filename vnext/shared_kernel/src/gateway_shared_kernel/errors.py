"""Stable canonical encoding error registry and exception type."""

from __future__ import annotations

from enum import StrEnum


class CanonicalErrorCode(StrEnum):
    """Closed formal registry of Shared Kernel stable error codes."""

    CANONICAL_INVALID_UTF8 = "CANONICAL_INVALID_UTF8"
    CANONICAL_INVALID_UNICODE = "CANONICAL_INVALID_UNICODE"
    CANONICAL_UNICODE_NONCHARACTER = "CANONICAL_UNICODE_NONCHARACTER"
    CANONICAL_JCS_SYNTAX_INVALID = "CANONICAL_JCS_SYNTAX_INVALID"
    CANONICAL_JCS_DUPLICATE_MEMBER = "CANONICAL_JCS_DUPLICATE_MEMBER"
    CANONICAL_JCS_NUMBER_OUT_OF_RANGE = "CANONICAL_JCS_NUMBER_OUT_OF_RANGE"
    CANONICAL_JCS_NON_FINITE_NUMBER = "CANONICAL_JCS_NON_FINITE_NUMBER"
    CANONICAL_IDENTIFIER_EMPTY = "CANONICAL_IDENTIFIER_EMPTY"
    CANONICAL_IDENTIFIER_COLLISION = "CANONICAL_IDENTIFIER_COLLISION"
    CANONICAL_TYPE_MISMATCH = "CANONICAL_TYPE_MISMATCH"
    CANONICAL_INTEGER_OUT_OF_RANGE = "CANONICAL_INTEGER_OUT_OF_RANGE"
    CANONICAL_DECIMAL_INVALID = "CANONICAL_DECIMAL_INVALID"
    CANONICAL_FLOAT_NON_FINITE = "CANONICAL_FLOAT_NON_FINITE"
    CANONICAL_TEMPORAL_INVALID = "CANONICAL_TEMPORAL_INVALID"
    CANONICAL_TIME_OUT_OF_RANGE = "CANONICAL_TIME_OUT_OF_RANGE"
    CANONICAL_ANOMALY_INVALID = "CANONICAL_ANOMALY_INVALID"
    CANONICAL_SCALAR_TAG_UNKNOWN = "CANONICAL_SCALAR_TAG_UNKNOWN"
    CANONICAL_SCALAR_TAG_RESERVED = "CANONICAL_SCALAR_TAG_RESERVED"
    CANONICAL_FRAME_TRUNCATED = "CANONICAL_FRAME_TRUNCATED"
    CANONICAL_ULEB128_NON_MINIMAL = "CANONICAL_ULEB128_NON_MINIMAL"
    CANONICAL_ULEB128_OVERFLOW = "CANONICAL_ULEB128_OVERFLOW"
    CANONICAL_FRAME_LENGTH_INVALID = "CANONICAL_FRAME_LENGTH_INVALID"
    CANONICAL_COLLECTION_SEMANTICS_UNKNOWN = "CANONICAL_COLLECTION_SEMANTICS_UNKNOWN"
    CANONICAL_COLLECTION_DUPLICATE_ITEM = "CANONICAL_COLLECTION_DUPLICATE_ITEM"
    CANONICAL_COLLECTION_DUPLICATE_KEY = "CANONICAL_COLLECTION_DUPLICATE_KEY"


FORMAL_STABLE_ERROR_CODES: frozenset[CanonicalErrorCode] = frozenset(CanonicalErrorCode)


class CanonicalEncodingError(Exception):
    """Production failure carrying a normative stable error code."""

    def __init__(self, code: CanonicalErrorCode, message: str = "") -> None:
        self.code = code
        super().__init__(message or code.value)

    @property
    def stable_code(self) -> str:
        return self.code.value
